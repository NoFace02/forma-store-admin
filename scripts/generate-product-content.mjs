import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('../', import.meta.url);
const products = [
  ['ceramic-mug', 'A rounded ceramic mug with a warm glazed finish and a comfortable handle. A simple companion for coffee, tea, and quiet breaks.'],
  ['desk-lamp', 'A compact desk lamp with an angled shade and a sturdy base. Its understated shape fits a focused home-office workspace.'],
  ['cotton-throw', 'A soft cotton throw with a woven stripe pattern and fringed edges. Adds a comfortable layer to a sofa, reading chair, or bed.'],
  ['oak-tray', 'A rectangular oak tray with a raised edge and a natural wood finish. Designed for keeping everyday essentials together.'],
  ['notebook', 'A cloth-covered notebook with a clean label panel and ribbon marker. A thoughtful place for notes, sketches, and daily plans.'],
  ['linen-tote', 'A reusable linen tote with long handles and a front pocket. A lightweight everyday bag for small essentials.'],
];
const quote = value => "'" + value.replaceAll("'", "''") + "'";
const values = products.map(([name, description], index) => {
  const svg = readFileSync(new URL(`assets/products/${name}.svg`, root), 'utf8').trim();
  return `(${index}, ${quote('data:image/svg+xml,' + encodeURIComponent(svg))}, ${quote(description)})`;
}).join(',\n');
const sql = `-- Generated by scripts/generate-product-content.mjs. Edit the SVG sources or generator instead.\n\nbegin;
create temporary table product_content (kind integer, thumbnail text, description text) on commit drop;
insert into product_content values
${values};
update public.forma_demo_records r set payload = r.payload || jsonb_build_object('thumbnail',c.thumbnail,'description',c.description) from product_content c where r.resource='products' and (r.id-1)%6=c.kind;
update forma_private.demo_seed s set payload = s.payload || jsonb_build_object('thumbnail',c.thumbnail,'description',c.description) from product_content c where s.resource='products' and (s.id-1)%6=c.kind;
commit;
`;
const destination = new URL('database/product-content.sql', root);
if (process.argv.includes('--check')) {
  if (readFileSync(destination, 'utf8').replaceAll('\r\n', '\n') !== sql) {
    throw new Error('Product SQL is out of date. Run pnpm generate:products.');
  }
} else {
  writeFileSync(destination, sql);
}
